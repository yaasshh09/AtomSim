"""Writes web/src/lib/luts.ts out of the matplotlib colormaps.

One color authority: the server thumbnails (matplotlib) and the browser client
read the same 256-entry tables, so a density looks identical in a
thumbnail, the cross-section canvas and the 3D cloud. Re-run this after a
matplotlib upgrade.
"""

from pathlib import Path

import matplotlib
import numpy as np

OUT = Path(__file__).resolve().parents[1] / "web" / "src" / "lib" / "luts.ts"


def rows(name: str) -> str:
    cmap = matplotlib.colormaps[name]
    rgb = (np.asarray(cmap(np.linspace(0.0, 1.0, 256)))[:, :3] * 255).round().astype(int)
    return ",\n".join(f"  [{r}, {g}, {b}]" for r, g, b in rgb)


def lab_to_srgb(lab: np.ndarray) -> np.ndarray:
    """CIELAB (D65) to sRGB in [0, 1], unclipped, so a caller can check the gamut."""
    L, a, b = lab[:, 0], lab[:, 1], lab[:, 2]
    fy = (L + 16) / 116
    fx = fy + a / 500
    fz = fy - b / 200

    def finv(f):
        return np.where(f**3 > 0.008856, f**3, (f - 16 / 116) / 7.787)

    xyz = np.stack([finv(fx) * 0.95047, finv(fy), finv(fz) * 1.08883], axis=1)
    lin = xyz @ np.array([
        [3.2406, -1.5372, -0.4986],
        [-0.9689, 1.8758, 0.0415],
        [0.0557, -0.2040, 1.0570],
    ]).T
    return np.where(
        lin <= 0.0031308, 12.92 * lin, 1.055 * np.abs(lin) ** (1 / 2.4) * np.sign(lin) - 0.055
    )


def phase_rows() -> str:
    """A cyclic map for arg(psi) that colour-blind readers can still read.

    An HSL hue wheel turns into near-identical colours for protanopes and
    deuteranopes: two phases 60 degrees or more apart fell within dE 0.4 of
    each other (tests/test_lut_cvd.py measures it). Every kind of dichromat
    keeps lightness, so lightness carries cos(phi); the sin(phi) half rides a
    hue direction with both a blue-yellow part (kept by protanopes and
    deuteranopes) and a red-green part (kept by tritanopes):
    L* = 60 + 22 cos(phi), a* = 10 sin(phi), b* = 30 sin(phi). Those numbers
    came out of a grid search for the largest worst-case separation, about
    dE 20 a sixth of a turn apart for all four kinds of vision, inside sRGB.
    L* stays inside [38, 82], off both the white and the black stage, so no
    phase disappears into either background.
    """
    phi = np.linspace(0.0, 2 * np.pi, 256, endpoint=False)
    lab = np.stack([60 + 22 * np.cos(phi), 10 * np.sin(phi), 30 * np.sin(phi)], axis=1)
    rgb = lab_to_srgb(lab)
    assert rgb.min() > -0.01 and rgb.max() < 1.01, "the phase ellipse left the sRGB gamut"
    rgb = (np.clip(rgb, 0, 1) * 255).round().astype(int)
    return ",\n".join(f"  [{r}, {g}, {b}]" for r, g, b in rgb)


TEMPLATE = """\
// GENERATED by scripts/gen_luts.py from matplotlib {version} - do not edit by hand.
// Single color authority: server thumbnails (matplotlib) and this client LUT
// come from the same colormaps, so densities look identical everywhere.

export type Lut = ReadonlyArray<readonly [number, number, number]>;

export const INFERNO: Lut = [
{inferno},
];

export const RDBU_R: Lut = [
{rdbu},
];

// arg(psi) from 0 (index 0) round to 2 pi: an ellipse through lightness and
// blue-yellow that stays readable with red-green colour blindness. Not a
// matplotlib map; see phase_rows() in scripts/gen_luts.py.
export const PHASE: Lut = [
{phase},
];
"""

OUT.write_text(
    TEMPLATE.format(version=matplotlib.__version__, inferno=rows("inferno"),
                    rdbu=rows("RdBu_r"), phase=phase_rows()),
    encoding="utf-8", newline="\n",
)
print(f"wrote {OUT}")
